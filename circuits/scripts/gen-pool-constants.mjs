// Writes the pool's zero values and the Poseidon hasher, so that the contract and the circuit cannot disagree.
import { readFileSync, writeFileSync } from "node:fs";
import { buildPoseidon, poseidonContract } from "circomlibjs";
import { createHash } from "node:crypto";

const DEPTH = 20;
const FIELD = 21888242871839275222246405745257275088548364400416034343698204186575808495617n;
const hash = await buildPoseidon();
const H = (a, b) => hash.F.toObject(hash([a, b]));

// Nobody knows a preimage for this, so an empty leaf cannot be spent as a note.
let zero = BigInt(`0x${createHash("sha256").update("vajra.pool.zero").digest("hex")}`) % FIELD;
const zeros = [];
for (let i = 0; i <= DEPTH; i++) {
  zeros.push(zero);
  zero = H(zero, zero);
}
const word = (v) => v.toString(16).padStart(64, "0");
writeFileSync(
  new URL("../../contracts/src/PoolZeros.sol", import.meta.url),
  `// SPDX-License-Identifier: MIT
pragma solidity 0.8.28;

/// The empty subtree at each level of the pool's Poseidon tree. Generated by circuits/scripts/gen-pool-constants.mjs.
library PoolZeros {
    bytes private constant ZEROS =
        hex"${zeros.map(word).join("")}";

    function at(uint256 level) internal pure returns (uint256 value) {
        bytes memory zeros = ZEROS;
        assembly ("memory-safe") {
            value := mload(add(add(zeros, 32), mul(level, 32)))
        }
    }
}
`,
);
writeFileSync(
  new URL("../../packages/core/src/artifacts/PoseidonT3.json", import.meta.url),
  JSON.stringify({ abi: poseidonContract.generateABI(2), bytecode: poseidonContract.createCode(2) }) + "\n",
);
writeFileSync(new URL("../../packages/core/src/pool-zeros.json", import.meta.url), JSON.stringify(zeros.map(String)) + "\n");
console.log(`zeros to level ${DEPTH}, root of the empty tree ${zeros[DEPTH]}`);
